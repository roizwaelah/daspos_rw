#!/usr/bin/env python3
"""
Convert DasPos backup JSON into SQL INSERT statements for Supabase staging tables.

Usage:
  python scripts/export_backup_to_staging_sql.py \
    --input /path/daspos_backup.json \
    --output /path/migration_batch.sql \
    --batch-id 11111111-1111-1111-1111-111111111111
"""

import argparse
import json
import uuid
from datetime import datetime, timezone
from typing import Any, Dict, List


MONTH_MAP = {
    "Jan": 1,
    "Feb": 2,
    "Mar": 3,
    "Apr": 4,
    "Mei": 5,
    "May": 5,
    "Jun": 6,
    "Jul": 7,
    "Agu": 8,
    "Aug": 8,
    "Sep": 9,
    "Okt": 10,
    "Oct": 10,
    "Nov": 11,
    "Des": 12,
    "Dec": 12,
}


def sql_quote(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value).replace("'", "''")
    return "'" + text + "'"


def parse_trx_at(date_text: str, time_text: str) -> str:
    # Input example: "17 Mar 2026", "15:03"
    parts = (date_text or "").split()
    if len(parts) != 3:
        return datetime.now(timezone.utc).isoformat()
    day_raw, month_raw, year_raw = parts
    month = MONTH_MAP.get(month_raw, 1)
    day = int(day_raw)
    year = int(year_raw)
    hh, mm = (time_text or "00:00").split(":")
    # Keep as UTC for deterministic import; adjust if you want local timezone.
    dt = datetime(year, month, day, int(hh), int(mm), tzinfo=timezone.utc)
    return dt.isoformat()


def load_backup(path: str) -> Dict[str, Any]:
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    for required in ("products", "users", "transactions"):
        if required not in data:
            raise ValueError(f"Invalid backup file: missing '{required}'")
    return data


def build_sql(batch_id: str, data: Dict[str, Any]) -> str:
    lines: List[str] = []
    lines.append("-- Generated by scripts/export_backup_to_staging_sql.py")
    lines.append(f"-- batch_id: {batch_id}")
    lines.append("begin;")
    lines.append("")

    for user in data.get("users", []):
        lines.append(
            "insert into public.migration_users_stg "
            "(batch_id, legacy_username, role, password_hash) values "
            f"({sql_quote(batch_id)}, {sql_quote(user.get('username'))}, "
            f"{sql_quote(user.get('role'))}, {sql_quote(user.get('passwordHash'))});"
        )

    lines.append("")
    for product in data.get("products", []):
        lines.append(
            "insert into public.migration_products_stg "
            "(batch_id, legacy_id, name, price, stock) values "
            f"({sql_quote(batch_id)}, {sql_quote(product.get('id'))}, "
            f"{sql_quote(product.get('name'))}, {sql_quote(product.get('price', 0))}, "
            f"{sql_quote(product.get('stock', 0))});"
        )

    lines.append("")
    for trx in data.get("transactions", []):
        trx_at = parse_trx_at(trx.get("date", ""), trx.get("time", ""))
        lines.append(
            "insert into public.migration_transactions_stg "
            "(batch_id, legacy_id, trx_at, total, pay, change_amount) values "
            f"({sql_quote(batch_id)}, {sql_quote(trx.get('id'))}, {sql_quote(trx_at)}, "
            f"{sql_quote(trx.get('total', 0))}, {sql_quote(trx.get('pay', 0))}, "
            f"{sql_quote(trx.get('change', 0))});"
        )
        for idx, item in enumerate(trx.get("items", []), start=1):
            lines.append(
                "insert into public.migration_transaction_items_stg "
                "(batch_id, transaction_legacy_id, line_no, legacy_product_id, product_name, price, qty) values "
                f"({sql_quote(batch_id)}, {sql_quote(trx.get('id'))}, {sql_quote(idx)}, "
                f"{sql_quote(item.get('productId'))}, {sql_quote(item.get('productName'))}, "
                f"{sql_quote(item.get('price', 0))}, {sql_quote(item.get('qty', 0))});"
            )

    lines.append("")
    lines.append("commit;")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, help="Path to daspos_backup.json")
    parser.add_argument("--output", required=True, help="Output SQL file path")
    parser.add_argument("--batch-id", default=str(uuid.uuid4()), help="Batch UUID")
    args = parser.parse_args()

    uuid.UUID(args.batch_id)
    backup = load_backup(args.input)
    sql_text = build_sql(args.batch_id, backup)

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(sql_text)

    print(f"OK: wrote {args.output}")
    print(f"batch_id={args.batch_id}")


if __name__ == "__main__":
    main()

